"""V2 (OUTLINE.md v3, Section 3): synthetic benchmarks with known answers, at scale.

Universes are random graphs with heavy-tailed degrees, of two kinds:
  unipartite  Chung-Lu graphs, like a knowledge graph's entity graph
  bipartite   user-item graphs with heterogeneous activity, like a recommendation log
in three sizes. A release is generated by one rule family at one threshold (threshold, both_ends,
seeds_neighbours, kcore; T in 2, 3, 5, 8), then perturbed: a share eps of its units is removed and the same number
of non-release units is added, at random. Two controls replace the rule by another release of the 3-core's size:
  random       a random unit set
  edge_sample  a rule outside the four families: relations are drawn at random and both ends kept until the
               release is large enough. It favours well-connected units, but has no threshold.

The answers are independent of the tool (added 2026-10-27, after the 2026-10-24 review). Releases, the recovery
check and the end-to-end releases come from `reference_units`, a plain-Python version of the four families written
from their definitions (sets, and a vertex-peeling k-core), which shares no code with benchscope_audit.rules. On
every graph it is also compared with the tool's rule_units over the whole search grid.

Measured, per run:
  W          the tool's unit-level W against a direct count, and (small graphs) the pair-level W against explicit
             enumeration of every unobserved pair; both must agree exactly
  recovery   whether the rule search (thresholds 1-20, all four families, as in the tool) returns the generating
             family and threshold, or another rule that selects exactly the generating units (by the reference)
  verdict    the search's verdict on the perturbed release, and the Jaccard of the generating rule with it
An end-to-end subset writes the universe and the release as files and runs the command line (kg-triples), so
that reading, id mapping and the card are checked too.

Outputs (results/validation/): v2_synthetic.tsv (one row per run), v2_reference_agreement.tsv (reference vs tool
per graph, family and threshold), v2_e2e.tsv, v2_summary.md.
usage: python -E -P validate_synthetic.py [OUT=results/validation]
"""
import itertools
import json
import os
import sys
import tempfile
import time

import numpy as np

P4 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(P4, '..', 'tool', 'src'))
from benchscope_audit import Universe, pair_exclusion, rule_units, search_rules, unit_exclusion  # noqa: E402
from benchscope_audit.cli import main as cli_main  # noqa: E402
from benchscope_audit.universes import from_pairs  # noqa: E402

FAMILIES = ('threshold', 'both_ends', 'seeds_neighbours', 'kcore')
CONTROLS = ('random', 'edge_sample')
TS = (2, 3, 5, 8)
NOISE = (0.0, 0.005, 0.01, 0.02, 0.05, 0.10)
REPS = 5
SIZES = {'small': (500, 1500), 'medium': (5000, 15000), 'large': (50000, 150000)}   # (units, relations), approx.
SEARCH = range(1, 21)


def chung_lu(n, m, rng):
    w = rng.pareto(1.5, n) + 0.5
    p = w / w.sum()
    a, b = rng.choice(n, size=int(m * 1.4), p=p), rng.choice(n, size=int(m * 1.4), p=p)
    e = np.stack([np.minimum(a, b), np.maximum(a, b)], 1)
    e = np.unique(e[e[:, 0] != e[:, 1]], axis=0)
    e = e[rng.permutation(len(e))[:m]]
    used = np.unique(e)
    remap = -np.ones(n, np.int64)
    remap[used] = np.arange(len(used))
    return Universe('chung-lu', units=np.array([f'e{i}' for i in range(len(used))], dtype=object), edges=remap[e])


def bipartite(n, m, rng):
    users, items = int(n * 0.6), n - int(n * 0.6)
    pu, pi = rng.pareto(1.5, users) + 0.2, rng.pareto(1.5, items) + 0.2
    a = rng.choice(users, size=int(m * 1.4), p=pu / pu.sum())
    b = rng.choice(items, size=int(m * 1.4), p=pi / pi.sum())
    pairs = np.unique(np.stack([a, b], 1), axis=0)
    pairs = pairs[rng.permutation(len(pairs))[:m]]
    return from_pairs([(f'u{x}', f'i{y}') for x, y in pairs.tolist()], name='bipartite')


def reference_units(edges, n, family, T):
    """The four rule families from their definitions, in plain Python; edges is a list of (a, b) unit indexes.
    Depth is a unit's number of relations. Returns the selected units as a set."""
    deg = [0] * n
    for a, b in edges:
        deg[a] += 1
        deg[b] += 1
    if family == 'threshold':                   # units with at least T relations
        return {v for v in range(n) if deg[v] >= T and deg[v] > 0}
    if family == 'both_ends':                   # ends of relations whose two ends both have at least T relations
        return {x for a, b in edges if deg[a] >= T and deg[b] >= T for x in (a, b)}
    if family == 'seeds_neighbours':            # units with at least T relations, plus every unit they relate to
        return {x for a, b in edges if deg[a] >= T or deg[b] >= T for x in (a, b)}
    if family == 'kcore':                       # peel units with fewer than T remaining relations until none is left
        nbrs = [[] for _ in range(n)]
        for a, b in edges:
            nbrs[a].append(b)
            nbrs[b].append(a)
        left, gone = deg[:], set()
        stack = [v for v in range(n) if left[v] < T]
        while stack:
            v = stack.pop()
            if v in gone:
                continue
            gone.add(v)
            for u in nbrs[v]:
                if u not in gone:
                    left[u] -= 1
                    if left[u] < T:
                        stack.append(u)
        return {v for v in range(n) if v not in gone and deg[v] > 0}
    raise ValueError(f'unknown family {family}')


def edge_sample_units(edges, k, rng):
    """The out-of-family control: draw relations at random and keep both ends until at least k units are kept."""
    keep = set()
    for i in rng.permutation(len(edges)).tolist():
        keep.update(edges[i])
        if len(keep) >= k:
            break
    return keep


def as_mask(n, units):
    m = np.zeros(n, bool)
    m[list(units)] = True
    return m


def set_jaccard(a, b):
    u = int((a | b).sum())
    return float((a & b).sum() / u) if u else 1.0


def perturb(true, eps, rng):
    k = int(round(eps * true.sum()))
    out = true.copy()
    if k:
        out[rng.choice(np.flatnonzero(true), size=k, replace=False)] = False
        out[rng.choice(np.flatnonzero(~true), size=min(k, int((~true).sum())), replace=False)] = True
    return out, k


def brute_pair_w(uni, mask):
    obs = {tuple(sorted(e)) for e in uni.edges.tolist()} if uni.part is None else {tuple(e) for e in uni.edges.tolist()}
    if uni.part is None:
        cand = [(a, b) for a, b in itertools.combinations(range(uni.n), 2) if (a, b) not in obs]
    else:
        us, its = np.flatnonzero(uni.part == 0).tolist(), np.flatnonzero(uni.part == 1).tolist()
        cand = [(a, b) for a in us for b in its if (a, b) not in obs]
    kept = sum(1 for a, b in cand if mask[a] and mask[b])
    return 1 - kept / len(cand), len(cand)


def one_run(uni, ref, kind, size, rep, rule, T, eps, true, rng, rows):
    share = true.sum() / uni.n
    if not 0.05 <= share <= 0.95:
        rows.append(dict(kind=kind, size=size, rep=rep, rule=rule, T=T, eps=eps, status='skipped: release share '
                         f'{share:.3f} outside [0.05, 0.95]'))
        return
    noisy, k = perturb(true, eps, rng)
    t0 = time.time()
    w_tool = unit_exclusion(uni, noisy, by_strata=False)['W']
    w_count = (uni.n - int(noisy.sum())) / uni.n
    res = search_rules(uni, noisy, thresholds=SEARCH)
    best = res['best']
    ruled = rule in FAMILIES
    gen = [f for f in res['families'] if f['family'] == rule][0] if ruled else None
    row = dict(kind=kind, size=size, rep=rep, rule=rule, T=T, eps=eps, status='ok', units=uni.n, relations=len(uni.edges),
               release=int(noisy.sum()), flipped=k, W_tool=w_tool, W_count=w_count, W_equal=w_tool == w_count,
               best_family=best['family'], best_T=best['T'], best_jaccard=best['jaccard'], verdict=best['verdict'],
               recovered_exact=(ruled and best['family'] == rule and best['T'] == T),
               recovered_equivalent=(ruled and np.array_equal(ref(best['family'], best['T']), true)),
               generating_rule_jaccard=(set_jaccard(true, noisy) if ruled else None),
               generating_family_best_T=(gen['T'] if gen else None), seconds=round(time.time() - t0, 3))
    if size == 'small':
        wp_tool = pair_exclusion(uni, noisy)['W_pairs']
        wp_brute, ncand = brute_pair_w(uni, noisy)
        row.update(Wpairs_tool=wp_tool, Wpairs_enumerated=wp_brute, Wpairs_equal=abs(wp_tool - wp_brute) < 1e-12,
                   candidate_pairs=ncand)
    rows.append(row)


def e2e(rows_out, tmp):
    """kg-triples on files: the card's W and best rule against the known answer (from the reference)."""
    rng = np.random.default_rng(20261024)
    for rep, (rule, T) in itertools.product(range(3), (('kcore', 3), ('kcore', 5), ('both_ends', 3), ('both_ends', 5))):
        uni = chung_lu(*SIZES['medium'], rng)
        edges = [tuple(x) for x in uni.edges.tolist()]
        keep = reference_units(edges, uni.n, rule, T)
        if rule == 'kcore':                                  # the relations among the core's units
            kept = [(a, b) for a, b in edges if a in keep and b in keep]
        else:                                                # the relations whose two ends both have >= T relations
            deg = np.bincount(np.array(edges).ravel(), minlength=uni.n)
            kept = [(a, b) for a, b in edges if deg[a] >= T and deg[b] >= T]
        d = os.path.join(tmp, f'{rule}{T}_{rep}')
        os.makedirs(os.path.join(d, 'release'), exist_ok=True)
        with open(os.path.join(d, 'universe.tsv'), 'w', encoding='utf-8', newline='\n') as f:
            f.writelines(f'{uni.units[a]}\tr\t{uni.units[b]}\n' for a, b in edges)
        e = np.array(kept)[rng.permutation(len(kept))]
        cut = [0, int(len(e) * 0.8), int(len(e) * 0.9), len(e)]
        for name, lo, hi in zip(('train', 'valid', 'test'), cut, cut[1:]):
            with open(os.path.join(d, 'release', f'{name}.txt'), 'w', encoding='utf-8', newline='\n') as f:
                f.writelines(f'{uni.units[a]}\tr\t{uni.units[b]}\n' for a, b in e[lo:hi].tolist())
        out = os.path.join(d, 'card.json')
        code = cli_main(['kg-triples', '--release', os.path.join(d, 'release'), '--universe', os.path.join(d, 'universe.tsv'),
                         '--format', 'tsv', '--name', f'synthetic {rule} {T}', '--out', out])
        card = json.load(open(out, encoding='utf-8')) if code == 0 else {}
        released = as_mask(uni.n, {x for ab in kept for x in ab})
        w_true = (uni.n - int(released.sum())) / uni.n
        best = (card.get('rule_diagnosis') or {}).get('best') or {}
        rows_out.append(dict(rep=rep, rule=rule, T=T, exit=code, units=uni.n, W_card=card.get('exclusion', {}).get('W'),
                             W_true=round(w_true, 6), W_equal=card.get('exclusion', {}).get('W') == round(w_true, 6),
                             best_family=best.get('family'), best_T=best.get('T'), best_jaccard=best.get('jaccard'),
                             recovered=(best.get('jaccard') == 1.0 and np.array_equal(
                                 as_mask(uni.n, reference_units(edges, uni.n, best['family'], best['T'])), released))
                             if best else False))


def write_tsv(path, rows):
    keys = []
    for r in rows:
        keys += [k for k in r if k not in keys]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\t'.join(keys) + '\n')
        for r in rows:
            f.write('\t'.join('' if r.get(k) is None else (f'{r[k]:.10g}' if isinstance(r[k], float) else str(r[k]))
                              for k in keys) + '\n')


def main(out):
    os.makedirs(out, exist_ok=True)
    rows, agree, t0 = [], [], time.time()
    for ki, (kind, gen) in enumerate((('unipartite', chung_lu), ('bipartite', bipartite))):
        for si, (size, (n, m)) in enumerate(SIZES.items()):
            for rep in range(REPS):
                rng = np.random.default_rng([20261024, ki, si, rep])
                uni = gen(n, m, rng)
                edges = [tuple(x) for x in uni.edges.tolist()]
                cache = {}

                def ref(family, T):
                    if (family, T) not in cache:
                        cache[(family, T)] = as_mask(uni.n, reference_units(edges, uni.n, family, T))
                    return cache[(family, T)]
                for fam, t in itertools.product(FAMILIES, SEARCH):
                    tool = rule_units(uni, fam, t)
                    agree.append(dict(kind=kind, size=size, rep=rep, family=fam, T=t, units_reference=int(ref(fam, t).sum()),
                                      units_tool=int(tool.sum()), equal=bool(np.array_equal(ref(fam, t), tool))))
                k3 = int(ref('kcore', 3).sum())
                for rule, T in [(f, t) for f in FAMILIES for t in TS] + [('random', None)]:
                    for eps in NOISE:
                        if rule == 'random':                 # a fresh random set per run, drawn as in the first version
                            true = np.zeros(uni.n, bool)
                            true[rng.choice(uni.n, size=k3, replace=False)] = True
                        else:
                            true = ref(rule, T)
                        one_run(uni, ref, kind, size, rep, rule, T, eps, true, rng, rows)
                crng = np.random.default_rng([20261027, ki, si, rep])   # the control added later has its own stream
                for eps in NOISE:
                    true = as_mask(uni.n, edge_sample_units(edges, k3, crng))
                    one_run(uni, ref, kind, size, rep, 'edge_sample', None, eps, true, crng, rows)
            print(f'{kind} {size}: {len(rows)} rows, {time.time() - t0:.0f} s', flush=True)
    write_tsv(os.path.join(out, 'v2_synthetic.tsv'), rows)
    write_tsv(os.path.join(out, 'v2_reference_agreement.tsv'), agree)
    e2e_rows = []
    with tempfile.TemporaryDirectory() as tmp:
        e2e(e2e_rows, tmp)
    write_tsv(os.path.join(out, 'v2_e2e.tsv'), e2e_rows)
    summarize(rows, agree, e2e_rows, os.path.join(out, 'v2_summary.md'), time.time() - t0)
    print('wrote', out)


def summarize(rows, agree, e2e_rows, path, seconds):
    ok = [r for r in rows if r['status'] == 'ok']
    ruled = [r for r in ok if r['rule'] in FAMILIES]
    small = [r for r in ok if 'Wpairs_equal' in r]
    skipped = {}
    for r in rows:
        if r['status'] != 'ok':
            skipped[r['rule']] = skipped.get(r['rule'], 0) + 1
    graphs = len({(a['kind'], a['size'], a['rep']) for a in agree})
    bad = [a for a in agree if not a['equal']]
    L = ['# V2: synthetic benchmarks with known answers', '',
         f'{len(rows)} runs ({len(ok)} used, {len(rows) - len(ok)} skipped because the release kept under 5% or over '
         f'95% of the units: ' + ', '.join(f'{k} {v}' for k, v in sorted(skipped.items())) + f'); {len(ruled)} '
         f'rule-generated; ' + ', '.join(f"{sum(r['rule'] == c for r in ok)} {c} controls" for c in CONTROLS)
         + f'; {seconds / 60:.1f} minutes.', '',
         '## The answers are independent of the tool', '',
         f'- Releases and the recovery check come from a plain-Python reference implementation of the four families. '
         f'On all {graphs} graphs, the reference and the tool select the same units for {len(agree) - len(bad)} of the '
         f'{len(agree)} family-threshold pairs of the search grid (4 families, thresholds 1-20).']
    L += [f"  - mismatch: {a['kind']} {a['size']} rep {a['rep']} {a['family']} T={a['T']}: reference "
          f"{a['units_reference']}, tool {a['units_tool']}" for a in bad[:20]]
    L += ['', '## W is exact', '',
          f'- Unit-level W equals the direct count in {sum(r["W_equal"] for r in ok)} of {len(ok)} runs.',
          f'- Pair-level W equals explicit enumeration of every unobserved pair in {sum(r["Wpairs_equal"] for r in small)} '
          f'of {len(small)} small-graph runs (up to {max(r["candidate_pairs"] for r in small):,} candidate pairs).', '',
          '## Recovery of the generating rule', '',
          '| noise eps | runs | generating rule recovered (same units) | same family and T | verdict reproduced | '
          'approximately | not reproduced | mean Jaccard of the generating rule |', '|---|---|---|---|---|---|---|---|']
    for eps in NOISE:
        rs = [r for r in ruled if r['eps'] == eps]
        n = len(rs)
        f = lambda c: f'{100 * sum(1 for r in rs if c(r)) / n:.1f}%'  # noqa: E731
        L.append(f'| {eps:g} | {n} | {f(lambda r: r["recovered_equivalent"])} | {f(lambda r: r["recovered_exact"])} | '
                 f'{f(lambda r: r["verdict"] == "reproduced")} | {f(lambda r: r["verdict"] == "approximately reproduced")} | '
                 f'{f(lambda r: r["verdict"] == "not reproduced")} | '
                 f'{np.mean([r["generating_rule_jaccard"] for r in rs]):.4f} |')
    L += ['', 'Without noise, by family (recovered = the best rule selects exactly the generating units):', '',
          '| family | runs | recovered | same family and T |', '|---|---|---|---|']
    for fam in FAMILIES:
        rs = [r for r in ruled if r['eps'] == 0 and r['rule'] == fam]
        L.append(f'| {fam} | {len(rs)} | {sum(r["recovered_equivalent"] for r in rs)} | {sum(r["recovered_exact"] for r in rs)} |')
    for c, what in (('random', 'random releases'), ('edge_sample', 'releases built by a rule outside the four families '
                                                                  '(random relations, both ends kept)')):
        L += ['', f'## Controls: {what}', '',
              '| noise eps | runs | verdict reproduced | approximately | not reproduced | max best Jaccard |',
              '|---|---|---|---|---|---|']
        for eps in NOISE:
            rs = [r for r in ok if r['rule'] == c and r['eps'] == eps]
            L.append(f'| {eps:g} | {len(rs)} | {sum(r["verdict"] == "reproduced" for r in rs)} | '
                     f'{sum(r["verdict"] == "approximately reproduced" for r in rs)} | '
                     f'{sum(r["verdict"] == "not reproduced" for r in rs)} | {max(r["best_jaccard"] for r in rs):.4f} |')
    L += ['', '## End to end (kg-triples on files)', '',
          f'- {len(e2e_rows)} runs; exit code 0 in {sum(r["exit"] == 0 for r in e2e_rows)}; the card\'s W equals the known W '
          f'(6 decimals) in {sum(bool(r["W_equal"]) for r in e2e_rows)}; the best rule selects exactly the released units in '
          f'{sum(bool(r["recovered"]) for r in e2e_rows)}.']
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(P4, 'results', 'validation'))
