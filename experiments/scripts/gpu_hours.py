"""GPU-hours of the WN18RR experiment per design (Appendix H), from stored accounting records only.

Sources:
  results/compute/sacct_20261028.txt    the cluster's accounting for the six job arrays (sacct -X -P, fetched
                                        2026-10-28): elapsed seconds and allocated GPUs per task
  results/compute/e1_seed0_summary.txt  the laptop script's wall time per model for E1 seed 0 (training and
                                        LibKGE's test, run one after another on one GPU)

GPU-hours = elapsed time x GPUs allocated, summed over tasks. The job ids come from the run log, which is not part of this copy. Per-query
scoring of the laptop runs, done afterwards, is not counted.

usage: python -E -P gpu_hours.py   (writes results/compute/gpu_hours.md)
"""
import csv
import os
import re

P4 = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
DIR = os.path.join(P4, 'results', 'compute')
JOBS = {'4268185': 'E1 seeds 1-4', '4268186': 'E2', '4269286': 'E2', '4286004': 'S3',
        '4270011': 'NBFNet E1 and deployment', '4268184': 'NBFNet feasibility'}
ORDER = ('E1 seed 0', 'E1 seeds 1-4', 'E2', 'S3', 'NBFNet E1 and deployment', 'NBFNet feasibility')


def main():
    runs, secs = dict.fromkeys(ORDER, 0), dict.fromkeys(ORDER, 0)
    with open(os.path.join(DIR, 'sacct_20261028.txt'), encoding='utf-8', newline='') as fh:
        for r in csv.DictReader(fh, delimiter='|'):
            assert r['State'] == 'COMPLETED', r['JobID']
            gpus = sum(int(t.split('=')[1]) for t in r['AllocTRES'].split(',') if t.startswith('gres/gpu='))
            d = JOBS[r['JobID'].split('_')[0]]
            runs[d] += 1
            secs[d] += int(r['ElapsedRaw']) * gpus
    with open(os.path.join(DIR, 'e1_seed0_summary.txt'), encoding='utf-8') as fh:
        for line in fh:
            runs['E1 seed 0'] += 1
            secs['E1 seed 0'] += int(re.search(r'wall=(\d+)s', line).group(1))
    lines = ['# GPU-hours per design (generated by scripts/gpu_hours.py)', '',
             '| design | where | runs | GPU-hours |', '|---|---|---|---|']
    for d in ORDER:
        lines.append(f"| {d} | {'laptop' if d == 'E1 seed 0' else 'cluster'} | {runs[d]} | {secs[d] / 3600:.2f} |")
    cluster = sum(secs[d] for d in ORDER if d != 'E1 seed 0')
    lines += [f'| cluster total | cluster | {sum(runs.values()) - runs["E1 seed 0"]} | {cluster / 3600:.2f} |',
              f'| total | both | {sum(runs.values())} | {sum(secs.values()) / 3600:.2f} |']
    with open(os.path.join(DIR, 'gpu_hours.md'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
